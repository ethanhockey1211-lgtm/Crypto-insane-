import { chromium } from "playwright";
const out = process.argv[2];
const browser = await chromium.launch({ executablePath: "/opt/pw-browsers/chromium" }).catch(async () => chromium.launch());
const page = await browser.newPage({ viewport: { width: 1600, height: 900 }, colorScheme: "dark" });
page.on("pageerror", (e) => console.log("PAGE ERROR", e.message));
page.on("console", (m) => { if (m.type() === "error") console.log("CONSOLE", m.text().slice(0, 200)); });
await page.goto("http://localhost:3000/", { waitUntil: "networkidle" });
await page.waitForTimeout(1500);
await page.screenshot({ path: `${out}/desktop.png` });
await page.getByRole("row", { name: /XRP/ }).first().click();
await page.waitForTimeout(2500);
await page.screenshot({ path: `${out}/drawer.png` });
await page.getByRole("button", { name: "heatmap" }).click();
await page.waitForTimeout(800);
await page.screenshot({ path: `${out}/heatmap.png` });
const mobile = await browser.newPage({ viewport: { width: 390, height: 844 }, colorScheme: "dark" });
await mobile.goto("http://localhost:3000/", { waitUntil: "networkidle" });
await mobile.waitForTimeout(1500);
await mobile.screenshot({ path: `${out}/mobile.png` });
await browser.close();
